async def run_trading_analyst(
    ticker: str,
    market_analysis_report: str,
    risk_tolerance: str = "moderate",
    investment_duration: str = "long-term",
    user_profile: Optional[Dict] = None,
) -> Dict:
    """
    Run the Trading Analyst Agent.

    Pipeline (ADK reference: trading_analyst_agent):
    1. Validate market_analysis_output is available (ADK: prerequisite check)
    2. Build user profile context from NirvanaX engines
    3. Generate 5+ strategies grounded in market analysis
    4. Enforce diversity across market outlooks
    5. Include Indian tax implications per strategy

    Args:
        ticker: Stock symbol
        market_analysis_report: Output from Data Analyst Agent (ADK: market_data_analysis_output)
        risk_tolerance: conservative | moderate | aggressive (ADK: user_risk_attitude)
        investment_duration: short-term | medium-term | long-term (ADK: user_investment_period)
        user_profile: NirvanaX engine outputs (stress score, emergency fund, savings rate)
    """
    # ADK prerequisite check: market analysis must be available
    if not market_analysis_report or len(market_analysis_report.strip()) < 50:
        return {
            "ticker": ticker.upper(),
            "strategies_report": (
                "⚠️ Error: Market analysis data is missing or incomplete. "
                "The Data Analyst Agent must complete its analysis before trading strategies can be generated. "
                "Please ensure Step 1 (Data Analysis) has been successfully completed."
            ),
            "error": "MISSING_MARKET_ANALYSIS",
            "analysis_complete": False,
        }

    start = time.time()

    # Build NirvanaX user profile context (enhancement over ADK)
    profile_context = ""
    if user_profile:
        profile_context = f"""
## NirvanaX User Financial Profile (Ground Truth from Deterministic Engines):
- Monthly Income: ₹{user_profile.get('monthly_income', 'N/A'):,.0f}
- Monthly Expenses: ₹{user_profile.get('monthly_expenses', 'N/A'):,.0f}
- Savings Rate: {user_profile.get('savings_rate', 'N/A')}%
- Financial Stress Score: {user_profile.get('stress_score', 'N/A')}/100
  (Score interpretation: <50 = High Stress/Defensive only, 50-75 = Moderate, >75 = Aggressive allowed)
- Emergency Fund Status: {user_profile.get('emergency_status', 'N/A')}
  (CRITICAL: If inadequate, equity/high-risk strategies must be deprioritized)

Strategy constraints from profile:
{"- Emergency fund inadequate: Prioritize capital preservation strategies. Avoid high-risk equity strategies." if user_profile.get('emergency_status') == 'inadequate' else "- Emergency fund adequate: Full strategy range available."}
{"- High stress score: Recommend defensive strategies only." if (user_profile.get('stress_score') or 100) < 50 else ""}
"""

    # Risk and duration descriptors (ADK: user_risk_attitude, user_investment_period)
    risk_map = {
        "conservative": "Conservative — capital preservation priority, maximum drawdown tolerance 10%, prefer low-volatility instruments",
        "moderate": "Moderate — balanced growth and protection, maximum drawdown tolerance 20%, accept normal market volatility",
        "aggressive": "Aggressive — maximum growth focus, drawdown tolerance >30%, willing to accept high volatility for higher returns",
    }
    duration_map = {
        "short-term": "Short-Term (<3 months) — momentum and technical setups, quick exits, STCG tax implications",
        "medium-term": "Medium-Term (3-12 months) — balance fundamentals with technicals, swing trading approach",
        "long-term": "Long-Term (>1 year) — fundamentals-driven, compounding focus, LTCG tax advantage after 1 year",
    }

    risk_desc = risk_map.get(risk_tolerance.lower(), risk_map["moderate"])
    duration_desc = duration_map.get(investment_duration.lower(), duration_map["long-term"])

    prompt = f"""Develop at least 5 distinct trading strategies for {ticker.upper()}.

## User Investment Profile:
- **Risk Attitude:** {risk_desc}
- **Investment Period:** {duration_desc}
{profile_context}

## Market Analysis Report (from Data Analyst Agent — market_data_analysis_output):
{market_analysis_report[:4000]}

## Your Task:
Based on the market analysis above and the user's profile, develop a MINIMUM of 5 diverse trading strategies.

MANDATORY strategy diversity:
1. One conservative/defensive strategy (suitable for capital preservation)
2. One growth/momentum strategy (suitable for trend following)
3. One income-generating strategy (dividends, covered calls, or yield focus)
4. One value/fundamental strategy (based on valuation metrics from the analysis)
5. One tactical/opportunistic strategy (based on specific catalysts from the analysis)

For EACH strategy, provide ALL of these components:
- **Strategy Name & Type**
- **Description & Rationale** (grounded in the market analysis data above)
- **Alignment with User Profile** (specific to {risk_tolerance} risk and {investment_duration} horizon)
- **Key Indian Market Indicators to Watch** (include NIFTY correlation, FII/DII flows, RBI sensitivity)
- **Entry Conditions** (specific, actionable triggers)
- **Exit Conditions & Targets** (specific price levels or percentage targets)
- **Stop-Loss Level** (specific percentage or technical level)
- **Primary Risks** (specific to this strategy)
- **Indian Tax Implications** (STCG 15% if <1 year, LTCG 10% above ₹1L if >1 year)
- **Estimated Return Potential** (realistic range based on analysis)

CRITICAL: Ground every strategy in the market analysis data. Reference specific findings.
If the analysis shows risks, reflect them in strategy design.
Format as professional markdown with clear section headers."""

    strategies_text = await _call_llm(prompt)

    if "disclaimer" not in strategies_text.lower():
        strategies_text += LEGAL_DISCLAIMER
    if "TRADING_ANALYSIS_COMPLETE" not in strategies_text:
        strategies_text += "\n\nTRADING_ANALYSIS_COMPLETE: TRUE"

    elapsed = round(time.time() - start, 2)

    return {
        "ticker": ticker.upper(),
        "strategies_report": strategies_text,
        "risk_tolerance": risk_tolerance,
        "investment_duration": investment_duration,
        "analysis_complete": True,
        "generated_at": datetime.utcnow().isoformat(),
        "latency_s": elapsed,
        "agent": "Trading Analyst Agent v2 (ADK-Enhanced)",
    }
