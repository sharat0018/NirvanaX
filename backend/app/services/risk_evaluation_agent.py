async def _call_llm(prompt: str) -> str:
    import asyncio as _aio

    # Try Gemini first with 429 retry
    if GEMINI_API_KEY:
        for attempt in range(2):
            try:
                async with httpx.AsyncClient(timeout=60.0) as client:
                    resp = await client.post(
                        f"{GEMINI_URL}?key={GEMINI_API_KEY}",
                        json={
                            "contents": [{"parts": [{"text": prompt}]}],
                            "systemInstruction": {"parts": [{"text": RISK_ANALYST_SYSTEM_PROMPT}]},
                            "generationConfig": {"maxOutputTokens": 3000, "temperature": 0.15},
                        },
                    )
                    if resp.status_code == 200:
                        return resp.json()["candidates"][0]["content"]["parts"][0]["text"].strip()
                    if resp.status_code == 429:
                        wait = 20 * (attempt + 1)
                        print(f"[RiskEval/Gemini] Rate limited, waiting {wait}s...")
                        await _aio.sleep(wait)
                        continue
                    print(f"[RiskEval/Gemini] HTTP {resp.status_code}")
                    break
            except Exception as e:
                print(f"[RiskEval/Gemini] {e}")
                break

    # Groq fallback with retry
    if GROQ_API_KEY:
        for attempt in range(2):
            try:
                async with httpx.AsyncClient(timeout=60.0) as client:
                    resp = await client.post(
                        GROQ_URL,
                        headers={"Authorization": f"Bearer {GROQ_API_KEY}", "Content-Type": "application/json"},
                        json={
                            "model": "llama-3.1-8b-instant",
                            "messages": [
                                {"role": "system", "content": RISK_ANALYST_SYSTEM_PROMPT},
                                {"role": "user", "content": prompt},
                            ],
                            "max_tokens": 3000,
                            "temperature": 0.15,
                        },
                    )
                    if resp.status_code == 200:
                        return resp.json()["choices"][0]["message"]["content"].strip()
                    if resp.status_code == 429:
                        wait = 15 * (attempt + 1)
                        print(f"[RiskEval/Groq] Rate limited, waiting {wait}s...")
                        await _aio.sleep(wait)
                        continue
                    print(f"[RiskEval/Groq] HTTP {resp.status_code}")
                    break
            except Exception as e:
                print(f"[RiskEval/Groq] {e}")
                break

    return _fallback_evaluation()


